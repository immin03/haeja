"""원고 표현 검수 (2026-11-12 대표: "어색한 표현들은 기획하고 스크립트 나온 후 한번 검수를 하고 렌더링")

렌더 전에 내레이션(lines)을 훑어 어색한 말·읽기 실수를 막는다. 롱폼 render2.preflight 와 쇼츠 gate.py 가 같이 쓴다.
새 어색한 표현을 대표님이 짚으면 WORDS 에 한 줄 추가한다.
"""
import re

# 어색한 말 → 바꿀 말
WORDS = {
    "웃돈": "프리미엄",
    "접는 폰": "폴더블폰", "접는 아이폰": "폴더블 아이폰", "접는 화면": "폴더블 화면",
    "석 달": "3달", "넉 달": "4달", "세 달": "3달", "네 달": "4달",  # 2026-11-23 대표 "석달은 3달로"
    "열에 하나": "10분의 1",
    "일곳": "한 곳",
    # 2026-11-17 대표(앤트로픽 편): "언어 관련 어색한 실수는 반복하지 말자"
    "줄기": "상당 부분·핵심 (뜻이 분명한 말로)",
    "지나가는 길": "영향권·파급 범위",
    "저의 생각": "제작진의 생각", "저희 생각": "제작진의 생각",
}
# 2026-11-16·17 대표: "1천억 원어치" → "1천억 원 규모의 물량", "모두 9억 원짜리" → "합계 9억 원짜리"
RX_WORDS = [(re.compile(r"(원|달러|위안|엔|유로|억|조|만)\s*어치"), "'어치' 금지 → 'N원 규모의 물량', 'N달러 물량'"),
            (re.compile(r"모두\s*\d[\d,.]*\s*(만|억|조)?\s*(원|달러)짜리"), "'모두 N원짜리' → '합계 N원짜리'")]
# 읽기 실수: 소수점 달러(331.90달러 → "삼백삼십일 점 구공 달러"로 읽힘) — "약 332달러"처럼 반올림하거나 "331달러 90센트"
# 2026-11-15 대표: "1TB를 1테라바이트라고 하지 1TB라고 안 하잖아 … 그런 거 하나 보자마자 AI가 했구나" — 숫자 뒤 영문 단위 약어는 내레이션·자막에 한글로 풀어 쓴다
UNITS = {"TB": "테라바이트", "GB": "기가바이트", "MB": "메가바이트", "KB": "킬로바이트", "Gb": "기가비트", "GW": "기가와트", "MW": "메가와트", "kW": "킬로와트",
         "kWh": "킬로와트시", "TWh": "테라와트시", "GWh": "기가와트시", "nm": "나노미터", "mm": "밀리미터", "cm": "센티미터", "km": "킬로미터", "kg": "킬로그램",
         "mAh": "밀리암페어시", "Hz": "헤르츠", "GHz": "기가헤르츠", "MHz": "메가헤르츠", "bp": "베이시스포인트", "%p": "%포인트", "oz": "온스", "t": "톤"}
UNIT_RX = re.compile(r"(\d[\d,.]*)\s?(" + "|".join(sorted(map(re.escape, UNITS), key=len, reverse=True)) + r")(?![A-Za-z])")
DEC_MONEY = re.compile(r"\d+\.\d+\s*(달러|위안|엔|유로|원)")


def check_lines(lines):
    errs = []
    for i, l in lines:
        for w, r in WORDS.items():
            if w in l:
                errs.append(f"장면 {i}: 어색한 말 '{w}' → '{r}'")
        for rx, msg in RX_WORDS:
            mm = rx.search(l)
            if mm:
                errs.append(f"장면 {i}: '{mm.group(0)}' — {msg}")
        m = DEC_MONEY.search(l)
        if m:
            errs.append(f"장면 {i}: 소수점 금액 '{m.group(0)}' — 읽으면 '점 구공'이 된다. 반올림(약 …) 또는 'N달러 M센트'")
        u = UNIT_RX.search(l)
        if u:
            errs.append(f"장면 {i}: 영문 단위 '{u.group(0)}' → '{u.group(1)}{UNITS[u.group(2)]}' — 내레이션·자막은 한글로 (AI가 쓴 티가 난다)")
    return errs
